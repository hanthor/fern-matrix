import { test, expect } from '@playwright/test'

// Localization foundation (#32): switching to Deutsch through the settings
// switcher retranslates the catalogued chrome and persists across reload,
// including the lock screen.
test('language switcher retranslates pilot surfaces', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Open settings' }).click()
  await expect(page.getByRole('button', { name: 'Security', exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Language' }).click()
  await page.getByText('Deutsch (Deutsch)').click()
  await expect(page.getByRole('button', { name: 'Sicherheit', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Darstellung', exact: true })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('lang', 'de')
  await page.keyboard.press('Escape')
  await expect(page.getByText('Deine Unterhaltungen')).toBeVisible()
  await expect(page.locator('.filter-tabs').getByRole('button', { name: 'Ungelesen' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Raumanruf starten' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Raummitglieder' })).toBeVisible()
  await expect(page.getByRole('searchbox', { name: 'Unterhaltungen suchen' })).toBeVisible()

  await page.reload()
  await page.getByRole('button', { name: 'Einstellungen öffnen' }).click()
  await expect(page.getByText('Mach es dir gemütlich')).toBeVisible()
  await expect(page.getByText('Kompakte Nachrichten')).toBeVisible()
  await page.getByRole('combobox', { name: 'Akzent' }).click()
  await page.getByRole('option', { name: 'Ocean' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-accent', 'ocean')
  expect(await page.locator('.fern-logo').evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(47, 93, 98)')
  await page.getByRole('combobox', { name: 'Akzent' }).click()
  await page.getByRole('option', { name: 'Fern' }).click()
  await expect(page.locator('html')).not.toHaveAttribute('data-accent')
  await expect(page.getByRole('button', { name: 'Sicherheit', exact: true })).toBeVisible()

  await page.getByRole('button', { name: 'Sicherheit', exact: true }).click()
  await expect(page.getByText('Deine Unterhaltungen gehören dir')).toBeVisible()
  await page.getByRole('button', { name: 'Konten', exact: true }).click()
  await expect(page.getByText('Alle deine Konten. Ein Zuhause.')).toBeVisible()
  await page.getByRole('button', { name: 'Konto hinzufügen' }).click()
  const loginDialog = page.getByRole('dialog', { name: 'Matrix-Konto hinzufügen' })
  await expect(loginDialog).toBeVisible()
  await expect(loginDialog.getByRole('button', { name: 'Weiter mit SSO' })).toBeVisible()
  await expect(loginDialog.getByRole('button', { name: 'Konto verbinden' })).toBeVisible()
  await loginDialog.getByRole('button', { name: 'Cancel' }).click()
  await expect(page.getByRole('textbox', { name: 'Nachrichtenfeld' })).toHaveAttribute('placeholder', 'Nachricht an #general')
  await expect(page.getByRole('button', { name: 'Nachricht senden' })).toBeVisible()
  await expect(page.getByText('Lokale Demo · Nachrichten bleiben in diesem Browser')).toBeVisible()
  await page.getByRole('textbox', { name: 'Nachrichtenfeld' }).fill('Deutscher Menütext')
  await page.getByRole('button', { name: 'Nachricht senden', exact: true }).click()
  const target = page.locator('article').filter({ hasText: 'Deutscher Menütext' }).last()
  await target.hover()
  await target.getByRole('button', { name: 'Nachrichtenaktionen' }).click()
  await expect(page.getByRole('menuitem', { name: 'Antworten' })).toBeVisible()
  await expect(page.getByRole('menuitem', { name: 'Text kopieren' })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Nachrichten suchen' }).click()
  await page.getByRole('searchbox', { name: 'Nachrichten suchen' }).fill('Deutscher')
  await expect(page.getByText(/\d+ Treffer/)).toBeVisible()
  await page.getByRole('button', { name: 'Alle Räume' }).click()
  await expect(page.getByRole('option', { name: 'Zu Nachricht in' })).toBeVisible()
  await expect(page.getByText('Nur geladene Nachrichten')).toBeVisible()
  await page.getByRole('searchbox', { name: 'Nachrichten suchen' }).fill('xyz-kein-treffer-123')
  await expect(page.getByText('Keine Treffer in geladenen Nachrichten.')).toBeVisible()
  await page.getByRole('button', { name: 'Rauminformationen' }).click()
  await expect(page.getByRole('complementary', { name: 'Raumdetails' })).toBeVisible()
  await expect(page.getByText('ÜBER DIESEN RAUM')).toBeVisible()
  await page.getByRole('button', { name: 'Mitglieder', exact: true }).click()
  await expect(page.getByText('PERSONEN IN DIESEM RAUM')).toBeVisible()
  await page.getByRole('button', { name: 'Pins', exact: true }).click()
  await expect(page.getByText('ANGEHEFTETE NACHRICHTEN')).toBeVisible()
  await page.getByRole('button', { name: 'Medien', exact: true }).click()
  await expect(page.getByText('GETEILT IN GELADENEN NACHRICHTEN')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Dateien', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Einstellungen öffnen' }).click()
  await page.getByRole('button', { name: 'Sicherheit', exact: true }).click()
  await page.getByLabel('Neue PIN').fill('2468')
  await page.getByLabel('PIN bestätigen').fill('2468')
  await page.getByRole('button', { name: 'Mit PIN sperren' }).click()
  await expect(page.getByRole('button', { name: 'Jetzt sperren' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('dialog', { name: 'Fern entsperren' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Willkommen zurück' })).toBeVisible()
  expect(errors).toEqual([])
})
